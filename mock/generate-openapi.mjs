#!/usr/bin/env node
// Generates docs/openapi/ews_api_v1.0.0.yaml: an OpenAPI 3.1 description of the DCI EWS
// interface as this suite tests it.
//
// The EWS standard publishes no OpenAPI YAML (spdci/api-standards has none for EWS). This file
// is DERIVED by the suite from the standard pages (API.EWS.01 - API.EWS.05, DO.EWS.01 -
// DO.EWS.06, CD.EWS.01 - CD.EWS.10, sdmx-dci-member-example) and from the schemas in
// test/features/support/helpers/schemas.js, so the documentation, the mocks and the tests
// always agree. Replace it with the published YAML once DCI releases one.
//   node mock/generate-openapi.mjs   (requires `npm install` in test/)

import { writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { definitions, envelopeDefinitions, itemFilters, codes } from '../test/features/support/helpers/schemas.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const YAML = createRequire(path.join(root, 'test', 'package.json'))('yaml');

// draft-07 "#/definitions/X" -> OpenAPI "#/components/schemas/X"
const relink = (schema) => JSON.parse(JSON.stringify(schema).replaceAll('"#/definitions/', '"#/components/schemas/'));
const ref = (name) => ({ $ref: `#/components/schemas/${name}` });
const jsonBody = (schema, description) => ({ required: true, description, content: { 'application/json': { schema } } });
const reply = (description, schema, type = 'application/json') => ({ description, content: { [type]: { schema } } });

const ack = { 200: reply('Acknowledgement (ACK, NACK or ERR)', ref('AckResponse')) };
const rejected = { 400: reply('The request does not conform: ERR acknowledgement', ref('AckResponse')) };
const ogcError = (description) => reply(description, ref('OgcException'));
const httpError = (description) => reply(description, ref('HttpErrorResponse'));

const allowed = (param) => (param === 'category' ? [...new Set([...codes.category, ...codes.categoryCode])] : codes[itemFilters[param]]);
const itemFilterParameters = [
  ...Object.keys(itemFilters).map((name) => ({ name, in: 'query', required: false, description: `CAP ${name} of the alert (or of one of its info blocks)`, schema: { type: 'string', enum: allowed(name) } })),
  { name: 'event', in: 'query', required: false, description: 'CAP event (Info.event), e.g. Flood', schema: { type: 'string' } },
  { name: 'event_code', in: 'query', required: false, description: 'CD.EWS.01 event type (Info.event_code), e.g. FL', schema: { type: 'string', enum: codes.eventType } },
  { name: 'limit', in: 'query', required: false, description: 'Maximum number of alerts returned', schema: { type: 'integer', minimum: 1 } },
];

const envelope = (name) => relink(envelopeDefinitions[name]);

const spec = {
  openapi: '3.1.0',
  info: {
    title: 'DCI Early Warning System (EWS) interface',
    version: '1.0.0',
    description: [
      'Interface between an Early Warning System (EWS) and a Social Protection (SP) system, per the',
      '[DCI Early Warning Systems standard](https://standards.spdci.org/standards/dci-standards/early-warning-systems).',
      '',
      '**Derived description.** The standard publishes no OpenAPI YAML for EWS. This document is generated by the',
      'EWS-Mockup-Compliance suite from the standard pages and the suite\'s schemas. Subscribe and notify use the DCI',
      'message envelope shared by every DCI API, since the standard publishes none for them.',
      '',
      '- API.EWS.01 Event subscription: `/subscribe`, `/unsubscribe` (EWS side) and their callbacks (SP side)',
      '- API.EWS.02 Event notification: `/notify` (SP side, EWS -> SP)',
      '- API.EWS.03 Fetch alert and API.EWS.04 Create-replace: `/collections/alerts` (EWS side, OGC API Features)',
      '- API.EWS.05 Aggregated member statistics: `/data/{dataflow}/{key}` (SP side, SDMX)',
    ].join('\n'),
  },
  servers: [{ url: 'https://ews.example.org', description: 'Early Warning System' }],
  tags: [
    { name: 'Subscription', description: 'API.EWS.01' },
    { name: 'Notification', description: 'API.EWS.02' },
    { name: 'Alerts', description: 'API.EWS.03, API.EWS.04 (OGC API Features)' },
    { name: 'Statistics', description: 'API.EWS.05, PRS.EWS.02 (SDMX)' },
  ],
  paths: {
    '/subscribe': {
      post: {
        tags: ['Subscription'], summary: 'Subscribe to alerts by event type, severity, area...', operationId: 'subscribe',
        description: 'The EWS acknowledges and sends the result (SubscribeResponse) to header.sender_uri (on-subscribe).',
        requestBody: jsonBody(envelope('subscribe')), responses: { ...ack, ...rejected },
      },
    },
    '/unsubscribe': {
      post: {
        tags: ['Subscription'], summary: 'Cancel subscriptions', operationId: 'unsubscribe',
        description: 'The EWS acknowledges and sends the result (UnSubscribeResponse) to header.sender_uri (on-unsubscribe).',
        requestBody: jsonBody(envelope('unsubscribe')), responses: { ...ack, ...rejected },
      },
    },
    '/on-subscribe': {
      post: {
        tags: ['Subscription'], summary: 'Receive the subscription result (SP side)', operationId: 'onSubscribe',
        servers: [{ url: 'https://spmis.example.org', description: 'SP system' }],
        requestBody: jsonBody(envelope('on-subscribe')), responses: { ...ack, ...rejected },
      },
    },
    '/on-unsubscribe': {
      post: {
        tags: ['Subscription'], summary: 'Receive the unsubscribe result (SP side)', operationId: 'onUnsubscribe',
        servers: [{ url: 'https://spmis.example.org', description: 'SP system' }],
        requestBody: jsonBody(envelope('on-unsubscribe')), responses: { ...ack, ...rejected },
      },
    },
    '/notify': {
      post: {
        tags: ['Notification'], summary: 'Receive alerts from the EWS (SP side)', operationId: 'notify',
        description: 'reg_records are CapAlert or Alert records, as named by reg_record_type. Only status "Actual" may drive action (CD.EWS.03).',
        servers: [{ url: 'https://spmis.example.org', description: 'SP system' }],
        requestBody: jsonBody(envelope('notify')), responses: { ...ack, ...rejected },
      },
    },
    '/collections/alerts': {
      get: {
        tags: ['Alerts'], summary: 'Describe the alerts collection', operationId: 'getAlertsCollection',
        responses: { 200: reply('The collection', ref('Collection')) },
      },
    },
    '/collections/alerts/items': {
      get: {
        tags: ['Alerts'], summary: 'Fetch alerts, filtered on CAP properties', operationId: 'getAlerts',
        parameters: itemFilterParameters,
        responses: { 200: reply('Alerts', ref('FeatureCollection'), 'application/geo+json'), 400: ogcError('Invalid filter value') },
      },
      post: {
        tags: ['Alerts'], summary: 'Create an alert', operationId: 'createAlert',
        requestBody: { required: true, content: { 'application/geo+json': { schema: ref('Alert') }, 'application/json': { schema: ref('Alert') } } },
        responses: { 201: reply('Created', ref('Alert'), 'application/geo+json'), 400: ogcError('Not a valid Alert Feature') },
      },
    },
    '/collections/alerts/items/{alertId}': {
      parameters: [{ name: 'alertId', in: 'path', required: true, schema: { type: 'string' }, description: 'Feature id (the CapAlert identifier)' }],
      get: {
        tags: ['Alerts'], summary: 'Fetch one alert', operationId: 'getAlert',
        responses: { 200: reply('The alert', ref('Alert'), 'application/geo+json'), 404: ogcError('Unknown alert') },
      },
      put: {
        tags: ['Alerts'], summary: 'Replace an alert', operationId: 'replaceAlert',
        requestBody: { required: true, content: { 'application/geo+json': { schema: ref('Alert') }, 'application/json': { schema: ref('Alert') } } },
        responses: { 200: reply('Replaced', ref('Alert'), 'application/geo+json'), 400: ogcError('Not a valid Alert Feature'), 404: ogcError('Unknown alert') },
      },
    },
    '/data/{dataflow}/{key}': {
      get: {
        tags: ['Statistics'], summary: 'Aggregated member statistics (SP side)', operationId: 'getMemberStatistics',
        description: 'Counts of registered members by REF_AREA.SEX.DISABILITY_STATUS.AGE_GROUP and TIME_PERIOD (API.EWS.05) or DENOMINATOR_TYPE (sdmx-dci-member-example). "*" is any value, "+" separates values. Counts below the minimum cell count are suppressed (null, CONFIDENTIALITY "C").',
        servers: [{ url: 'https://spmis.example.org', description: 'SP system' }],
        parameters: [
          { name: 'dataflow', in: 'path', required: true, schema: { type: 'string', enum: ['DCI_MEMBER_STATISTICS'] } },
          { name: 'key', in: 'path', required: true, schema: { type: 'string' }, example: 'AREA001.*.*.ALL.2026' },
          { name: 'format', in: 'query', required: false, schema: { type: 'string', enum: ['sdmx-json', 'dci-json'], default: 'sdmx-json' } },
        ],
        responses: {
          200: {
            description: 'Aggregated statistics',
            content: { 'application/vnd.sdmx.data+json': { schema: ref('SdmxJson') }, 'application/json': { schema: ref('DciStatistics') } },
          },
          400: httpError('Invalid key or format'),
          404: httpError('Unknown dataflow, or no results for the key'),
        },
      },
    },
  },
  components: { schemas: relink(definitions) },
};

mkdirSync(path.join(root, 'docs', 'openapi'), { recursive: true });
const header = '# DERIVED by EWS-Mockup-Compliance (mock/generate-openapi.mjs) from the DCI EWS standard pages:\n# the standard publishes no OpenAPI YAML. Do not edit by hand.\n';
writeFileSync(path.join(root, 'docs', 'openapi', 'ews_api_v1.0.0.yaml'), header + YAML.stringify(spec, { aliasDuplicateObjects: false, lineWidth: 0 }));
console.log('Generated docs/openapi/ews_api_v1.0.0.yaml');
